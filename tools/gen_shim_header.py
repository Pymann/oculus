#!/usr/bin/env python3
"""Generates the C header of the in-process Clang shim from its AIML specification.

    tools/gen_shim_header.py out/gen/oculus_shim.h src/frontend/clang_shim.aiml \
        src/frontend/inproc_frontend.aiml

Every enum of the AIML files becomes a C enum with values `<Enum>_<value>`, and
every one-line `def` of an `extern: "C"` block becomes an `extern "C"` prototype.  The
shim (worker/oculus_shim.cpp) includes the header, so a definition that does not
match the specification does not compile.  The AIML files are read line by line:
one enum value and one def per line (see the header of clang_shim.aiml).
"""

import re
import sys

ARG_TYPES = {"string": "const char *", "ptr": "void *", "i32": "int32_t"}
RETURN_TYPES = {"string": "char *", "ptr": "void *", "i32": "int32_t", "void": "void"}

ENUM_START = re.compile(r"^- enum:\s*$")
ENUM_NAME = re.compile(r"^\s+name:\s*(\w+)\s*$")
ENUM_VALUE = re.compile(r"^\s+-\s+(\w+)(?::\s*(-?\d+))?\s*$")
DEF_LINE = re.compile(r"^\s+- def: \{ name: (\w+), args: \[(.*)\], return: (\w+) \}\s*$")
ARG = re.compile(r"\[(\w+), (\w+)\]")


def parse(lines):
    enums = []
    defs = []
    current = None
    for line in lines:
        if ENUM_START.match(line):
            current = {"name": None, "values": [], "next": 0}
            enums.append(current)
            continue
        if line.startswith("- "):
            current = None
        if current is not None:
            named = ENUM_NAME.match(line)
            if named and current["name"] is None:
                current["name"] = named.group(1)
                continue
            value = ENUM_VALUE.match(line)
            if value and current["name"] is not None:
                number = int(value.group(2)) if value.group(2) is not None else current["next"]
                current["values"].append((value.group(1), number))
                current["next"] = number + 1
                continue
        found = DEF_LINE.match(line)
        if found:
            args = ARG.findall(found.group(2))
            defs.append((found.group(1), args, found.group(3)))
    return enums, defs


def c_param(kind, name):
    ctype = ARG_TYPES[kind]
    return ctype + name if ctype.endswith("*") else ctype + " " + name


def render(enums, defs, source):
    out = [
        "// Generated by tools/gen_shim_header.py from " + source + "; do not edit.",
        "#pragma once",
        "",
        "#include <stdint.h>",
        "",
    ]
    for enum in enums:
        out.append("enum " + enum["name"] + " {")
        for name, number in enum["values"]:
            out.append("    " + enum["name"] + "_" + name + " = " + str(number) + ",")
        out.append("};")
        out.append("")
    out.append('extern "C" {')
    for name, args, ret in defs:
        params = ", ".join(c_param(kind, arg) for arg, kind in args) or "void"
        out.append(RETURN_TYPES[ret] + " " + name + "(" + params + ");")
    out.append("}")
    out.append("")
    return "\n".join(out)


def main():
    if len(sys.argv) < 3:
        sys.stderr.write("usage: gen_shim_header.py OUT.h SPEC.aiml...\n")
        return 2
    lines = []
    for name in sys.argv[2:]:
        with open(name, encoding="utf-8") as spec:
            lines.extend(spec.read().splitlines())
    enums, defs = parse(lines)
    if not defs or not enums:
        sys.stderr.write("gen_shim_header.py: no enums or defs found\n")
        return 1
    with open(sys.argv[1], "w", encoding="utf-8") as header:
        header.write(render(enums, defs, " and ".join(sys.argv[2:])))
    return 0


if __name__ == "__main__":
    sys.exit(main())
